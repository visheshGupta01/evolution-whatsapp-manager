/* =========================================================
   LOGOUT / DISCONNECT
   ========================================================= */

app.post("/api/sessions/:instance/disconnect", async (req, res) => {
  const instance = String(req.params.instance || "").trim();

  try {
    let data;

    /**
     * Evolution v2 normally uses:
     *
     * DELETE /instance/logout/:instance
     *
     * Keep the fallback for installations exposing
     * the older disconnect route.
     */
    try {
      ({ data } = await evolutionRequest({
        method: "DELETE",
        url: `/instance/logout/${encodeURIComponent(instance)}`,
      }));
    } catch (logoutError) {
      if (![404, 405].includes(logoutError?.response?.status)) {
        throw logoutError;
      }

      ({ data } = await evolutionRequest({
        method: "POST",
        url: `/instance/disconnect/${encodeURIComponent(instance)}`,
      }));
    }

    return res.json(data);
  } catch (error) {
    return sendEvolutionError(res, error);
  }
});

/* =========================================================
   DELETE SESSION
   ========================================================= */

app.delete("/api/sessions/:instance", async (req, res) => {
  const instance = String(req.params.instance || "").trim();

  try {
    const { data } = await evolutionRequest({
      method: "DELETE",
      url: `/instance/delete/${encodeURIComponent(instance)}`,
    });

    tokens.delete(instance);

    return res.json(data);
  } catch (error) {
    return sendEvolutionError(res, error);
  }
});

/* =========================================================
   SEND TEXT MESSAGE
   ========================================================= */

app.post("/api/sessions/:instance/send-text", async (req, res) => {
  const instance = String(req.params.instance || "").trim();

  /**
   * Keep only digits.
   *
   * Example:
   *
   * +91 98765 43210
   *
   * becomes:
   *
   * 919876543210
   */
  const number = String(req.body?.number || "").replace(/\D/g, "");

  const text = String(req.body?.text || "").trim();

  if (!number || !text) {
    return res.status(400).json({
      message: "number and text are required",
    });
  }

  try {
    const { data } = await evolutionRequest({
      method: "POST",
      url: `/message/sendText/${encodeURIComponent(instance)}`,
      data: {
        number,
        text,
      },
    });

    return res.json(data);
  } catch (error) {
    return sendEvolutionError(res, error);
  }
});

/* =========================================================
   STATIC FRONTEND
   ========================================================= */

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const clientDist = path.resolve(__dirname, "../../client/dist");

app.use(express.static(clientDist));

/**
 * SPA fallback.
 *
 * Do not intercept API requests.
 */
app.use((req, res, next) => {
  if (req.path.startsWith("/api/")) {
    return next();
  }

  return res.sendFile(path.join(clientDist, "index.html"), (error) => {
    if (error) {
      return next();
    }
  });
});

/* =========================================================
   START SERVER
   ========================================================= */

app.listen(port, () => {
  console.log(
    `Evolution WhatsApp Manager listening on http://localhost:${port}`,
  );

  console.log(`Evolution API: ${evolutionUrl || "(not configured)"}`);

  console.log(`Evolution API key: ${evolutionKey ? "configured" : "MISSING"}`);
});
